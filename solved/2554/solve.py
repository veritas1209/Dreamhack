# 보내주신 헥사 데이터
encrypted_data = [
    0x35, 0x46, 0x39, 0x43, 0x25, 0x2e, 0x0c, 0x04, 0x00, 0x12, 0x12, 0x03,
    0x28, 0x30, 0x37, 0x1a, 0x30, 0x0e, 0x02, 0x46, 0x28, 0x46, 0x04, 0x28,
    0x13, 0x12, 0x1b, 0x1e, 0x14, 0x1e, 0x18, 0x02, 0x04, 0x0a
]

# XOR 키
key = 0x77

# 복호화
