        mut = (t + table[(~t ^ idx) & 0xFF]) & 0xFF
        if mut in available_targets:
            new_targets = available_targets.copy()
            new_targets.remove(mut)
            yield from find_all_pw_tmps(idx + 1, current_tmp + [t], new_targets)

