def get_idx(c0, c1):
    s_c0 = c0 if c0 < 128 else c0 - 256
    s_c1 = c1 if c1 < 128 else c1 - 256
    ebx = (s_c0 >> 4) | ((c0 << 4) & 0xFF)
    return (s_c1 >> 5) ^ ebx

