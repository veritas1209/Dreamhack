# DAT_00106020에서 추출한 헥사값들 (종료 조건이 나올 때까지만)
dat = [
    0x31,    0x63,    0x30,    0x2c,    0x29,    0x4d,    0x3e,    0x33,
    0x24,    0xe7,    0xd1,    0xbf,    0xa0,    0x8a,    0xa1,    0x57,
    0x32,    0x11,    0xef,    0xfa,    0xa2,    0xa8,    0x4d,    0x20,
    0xf6,    0xbf,    0x90,    0x8b,    0x51,    0x1a,    0xb3,    0x71,
    0x38,    0x20,    0xdf,    0x9c,    0x51,    0x0d,    0xc2,    0x71,
]

flag = ""
for i in range(len(dat)):
    # 수식: (i * i + dat[i]) % 256
    val = (i * i + dat[i]) & 0xFF
    
    # 계산된 값이 0이면 문자열의 끝 (Break)
    if val == 0:
        break
        
    flag += chr(val)

print(f"Flag: DH{{{flag}}}")