def calculate_lat():
    # 256x256 크기의 LAT 초기화
    lat = [[0] * 256 for _ in range(256)]
    
    # 모든 입력값 x에 대해 계산
    for x in range(256):
        sx = sbox[x]
        for a in range(256): # 입력 마스크
            for b in range(256): # 출력 마스크
                # 입력 마스크와 출력 마스크의 패리티 계산 (비트 내적)
                in_parity = bin(x & a).count('1') % 2
                out_parity = bin(sx & b).count('1') % 2
                
                # 패리티가 같으면 카운트 증가
                if in_parity == out_parity:
                    lat[a][b] += 1
                    
    return lat

def find_best_masks(lat):
    max_bias = 0
    best_pairs = []
    
    # 0, 0 마스크는 의미가 없으므로 1부터 시작
    for a in range(1, 256):
        for b in range(1, 256):
            # 이상적인 값 128(256의 절반)에서 얼마나 벗어났는지 계산
            bias = abs(lat[a][b] - 128)
            
            if bias > max_bias:
                max_bias = bias
                best_pairs = [(a, b, lat[a][b] - 128)]
            elif bias == max_bias:
                best_pairs.append((a, b, lat[a][b] - 128))
                
    return max_bias, best_pairs

print("[*] S-box LAT 계산 중...")
lat = calculate_lat()
max_bias, best_pairs = find_best_masks(lat)

print(f"[*] 최대 편향(Max Bias): {max_bias}/256 (확률: {0.5 + max_bias/256:.4f} 또는 {0.5 - max_bias/256:.4f})")
print("[*] 최적의 마스크 쌍 (Input Mask, Output Mask, Bias):")
for a, b, bias in best_pairs:
    print(f"    - Input: 0x{a:02x}, Output: 0x{b:02x}, Bias: {bias}")

