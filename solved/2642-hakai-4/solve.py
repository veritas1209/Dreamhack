    while True:
        uVar11 = 0
        uVar24 = uVar10 & 0xf
        uVar10 = (uVar10 >> 4) & 0xf
        
        for _ in range(4):
            uVar4 = uVar24
            uVar26 = (uVar11 + 1) & 0xffffffff
            rol1 = ((uVar4 >> 3) | (uVar4 << 1)) & 0xf
            t2 = (uVar11 + uVar4) & 0xffffffff
            t3 = (((uVar11 ^ 0x5d) * 3) + uVar4 * 7) & 0xffffffff
            uVar24 = ((rol1 ^ t2 ^ t3) & 0xf) ^ uVar10
            uVar11 = uVar26
            uVar10 = uVar4
            
        uVar10 = ((uVar4 << 4) | uVar24) & 0xffffffff
        if (uVar10 & 0xff) <= 0xe0:
            break
    return uVar10 & 0xff

