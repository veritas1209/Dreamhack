# 1. 대상 메모리 값 (기존에 추출한 32바이트)
target = [
    0xf8, 0xe0, 0xe6, 0x9e, 0x7f, 0x32, 0x68, 0x31, 
    0x05, 0xdc, 0xa1, 0xaa, 0xaa, 0x09, 0xb3, 0xd8, 
    0x41, 0xf0, 0x36, 0x8c, 0xce, 0xc7, 0xac, 0x66, 
    0x91, 0x4c, 0x32, 0xff, 0x05, 0xe0, 0xd9, 0x91
]

# 2. 어셈블리 덤프에서 찾아낸 Key 배열들
key1 = [0xde, 0xad, 0xbe, 0xef]
key2 = [0xef, 0xbe, 0xad, 0xde]
key3 = [0x11, 0x33, 0x55, 0x77, 0x99, 0xbb, 0xdd]

flag = ""

# 3. 32바이트 각각에 대해 역연산 수행
for i in range(32):
    c = target[i]
    
    # 과정 7의 역연산: XOR key3
    c ^= key3[i % len(key3)]
    
    # 과정 6의 역연산: - 0xf3
    c = (c - 0xf3) % 256
    
    # 과정 5의 역연산: + 0x4d
    c = (c + 0x4d) % 256
    
    # 과정 4의 역연산: XOR key2
    c ^= key2[i % len(key2)]
    
    # 과정 3의 역연산: + 0x5a
    c = (c + 0x5a) % 256
    
    # 과정 2의 역연산: - 0x1f
    c = (c - 0x1f) % 256
    
    # 과정 1의 역연산: XOR key1
    c ^= key1[i % len(key1)]
    
    flag += chr(c)

print(f"DH{{{flag}}}")