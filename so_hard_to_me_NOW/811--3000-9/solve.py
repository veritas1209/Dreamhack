# --- 1. Galois Field 연산 ---
def mul(a, b):
    p = 0
    for _ in range(8):
        if b & 1: p ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi: a ^= 0x11B  # 올바른 AES 다항식
        b >>= 1
    return p

def gf_inv(a):
    if a == 0: return 0
    for b in range(1, 256):
        if mul(a, b) == 1: return b
    return 0

# --- 2. 커스텀 S-Box ---
INV_CUSTOM_SBOX = [0] * 256
for i in range(256):
    b = gf_inv(i)
    b ^= ((b << 2) & 0xFF)
    b ^= ((b << 2) & 0xFF)
    b ^= (b >> 2)
    b ^= (b >> 1)
    b ^= 99
    INV_CUSTOM_SBOX[b] = i

def inv_sub_bytes(state):
    return [INV_CUSTOM_SBOX[b] for b in state]

# 🚨 이 배열 인덱스 오타 때문에 모든 게 망가졌었습니다. 🚨
# 암호화는 우측 시프트였으므로, 복호화는 반드시 '좌측'으로 당깁니다.
def inv_shift_rows(s):
    return [s[0],  s[5],  s[10], s[15],
            s[4],  s[9],  s[14], s[3],
            s[8],  s[13], s[2],  s[7],
            s[12], s[1],  s[6],  s[11]]

def xor_bytes(state, key):
    return [s ^ k for s, k in zip(state, key)]

def sum_xor(arr):
    r = 0
    for x in arr: r ^= x
    return r

# --- 3. 🚨 손실 압축 역연산 (256 다중 우주 탐색 알고리즘) 🚨 ---
def solve_A(A_prime):
    # 유효한 MixColumns 출력이려면 모든 바이트의 XOR 합이 무조건 0이어야 함!
    if sum_xor(A_prime) != 0:
        return []
    
    candidates = []
    for k in range(256):
        A = [0] * 16
        A[0] = k
        A[3] = A_prime[3] ^ A[0]
        A[6] = A_prime[6] ^ A[3]
        A[9] = A_prime[9] ^ A[6]
        A[12] = A_prime[12] ^ A[9]
        A[15] = A_prime[15] ^ A[12]
        A[2] = A_prime[2] ^ A[15]
        A[5] = A_prime[5] ^ A[2]
        A[8] = A_prime[8] ^ A[5]
        A[11] = A_prime[11] ^ A[8]
        A[14] = A_prime[14] ^ A[11]
        A[1] = A_prime[1] ^ A[14]
        A[4] = A_prime[4] ^ A[1]
        A[7] = A_prime[7] ^ A[4]
        A[10] = A_prime[10] ^ A[7]
        A[13] = A_prime[13] ^ A[10]
        candidates.append(A)
    return candidates

def decrypt_custom_aes(ciphertext, key_set):
    state = list(ciphertext)
    
    # 마지막 라운드 (Round 16)
    state = inv_shift_rows(state)
    state = inv_sub_bytes(state)
    state = xor_bytes(state, key_set[15])
    
    # BFS 다중 우주 탐색 큐
    paths = [state]
    
    # 15 ~ 1 라운드 역연산
    for i in range(14, -1, -1):
        next_paths = []
        for s in paths:
            A_prime = [gf_inv(b) for b in s]
            cands = solve_A(A_prime)
            for A in cands:
                prev_s = xor_bytes(inv_sub_bytes(inv_shift_rows(A)), key_set[i])
                
                # 이전 라운드의 결과가 수학적 모순이 없는 진짜 우주인지 검증 (가지치기)
                if i > 0:
                    if sum_xor([gf_inv(b) for b in prev_s]) == 0:
                        next_paths.append(prev_s)
                else:
                    next_paths.append(prev_s)
        
        paths = next_paths
        if not paths:
            return "Failed!"

    # 256^15 의 우주를 뚫고 살아남은 단 하나의 진짜 평문!
    if len(paths) > 0:
        return bytes(paths[0]).decode('ascii', errors='ignore').rstrip('\x00')
            
    return "Failed!"

